/**
 * หัวหน้าภาค ขั้น 7 "เวลาปิดนัดงานพรุ่งนี้" — เวลาปิดเป็นค่าที่แอดมินตั้งจริง ไม่ใช่ "16:00" ที่เขียนตายไว้ (เจ้าของงานตอบ 4.2)
 * แอดมินเปลี่ยนได้ 15:00–17:00 ถ้าเขียนตายไว้ กล่องจะบอกเวลาที่ผิดตั้งแต่วันที่เปลี่ยน
 * ค่ามาจากคำตอบรายการชุดเดียวกับแถบ "รอนัดวัน" (MyQueue ส่งผ่าน useHowToContext) — กล่องกับแถบบอกเวลาเดียวกันเสมอ
 * ยังไม่รู้ค่า (รายการยังไม่มา) ใช้คำในร่างเดิม — ไม่เดาเวลา
 * ป้ายปุ่ม "ร้านต้องการพรุ่งนี้จริง — ขอแอดมินแก้เป็นงานด่วน" = ASK_TOMORROW ใน components/DispatchCutoff.tsx
 * (ไม่ import ตัวแปรนั้น: ไฟล์ข้อความต้องไม่ดึงคอมโพเนนต์เข้ามา — ดูหัว utils/howtoTypes.ts) เปลี่ยนป้ายที่นั่นต้องแก้ที่นี่ด้วย
 */
export function cutoffBody(ctx: HowToCtx): string {
  const until = ctx.cutoff ? `พรุ่งนี้นัดได้ถึง ${timeText(ctx.cutoff.time)}` : "พรุ่งนี้นัดได้ถึงเวลาปิด (ปกติ 16:00 น.)";
  return `วันนี้นัดไม่ได้ · ${until} — 3 ชม. ก่อนปิด แถบ "รอนัดวัน" ขึ้นตรงนี้ · เลยเวลาแต่ร้านต้องการวันนั้นจริง กด "ร้านต้องการพรุ่งนี้จริง — ขอแอดมินแก้เป็นงานด่วน" ใต้ปฏิทินในฟอร์มนัดวัน`;
}

