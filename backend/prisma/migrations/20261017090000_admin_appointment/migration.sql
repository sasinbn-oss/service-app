-- ลำดับใหม่ (ต.ค. 69): แอดมินนัดลูกค้า → ลูกค้าคอนเฟิร์ม → หัวหน้าภาคจ่ายงาน
--
-- ไม่เปลี่ยนโครงตาราง เปลี่ยนแค่ความหมายของสถานะ ASSIGNED
--   เดิม  ASSIGNED = จ่ายทีมแล้ว รอหัวหน้าภาคนัดลูกค้า
--   ใหม่  ASSIGNED = ลูกค้าคอนเฟิร์มแล้ว รอหัวหน้าภาคจ่ายงาน
-- ใบที่ค้างอยู่ ASSIGNED แบบเดิมยังไม่ได้นัด จึงย้ายไปรอแอดมินนัด (PARTS_CHECKED)
-- ทีมเดิมคงไว้ — หัวหน้าภาคเห็นเป็นค่าตั้งต้นตอนจ่ายงานอีกครั้ง
-- ใบที่รอคอนเฟิร์ม (AWAITING_CONFIRM) ไม่ต้องย้าย: คอนเฟิร์มแล้วจะไปที่หัวหน้าภาคจ่ายงานตามลำดับใหม่
UPDATE "WorkOrder" SET "status" = 'PARTS_CHECKED' WHERE "status" = 'ASSIGNED';
