-- ชื่อไฟล์แนบภาษาไทยที่ถูกเก็บเป็นอักษรเพี้ยน (เจ้าของงานตัดสิน พ.ย. 69 — ซ่อมทั้งชื่อไฟล์และข้อความในประวัติ)
--
-- multer อ่านชื่อไฟล์ในคำขอแบบ latin1 ตามค่าตั้งต้น ทั้งที่เบราว์เซอร์ส่งเป็น UTF-8 — "ใบเสนอราคา.pdf" จึงถูกเก็บเป็น
-- "à¹\u0083à¸\u009a…" (ไบต์ UTF-8 แต่ละตัวกลายเป็นอักษร latin1 หนึ่งตัว) ทั้งในการ์ดไฟล์ ชื่อตอนโหลด และประวัติใบงาน
-- เส้นทางแนบไฟล์แก้ให้อ่านเป็น UTF-8 แล้ว ไฟล์นี้ซ่อมแถวที่เก็บไปก่อนหน้า
--
-- ซ่อมเฉพาะค่าที่ "ย้อนกลับได้สะอาด": ทุกตัวอักษรอยู่ในช่วง latin1 และไบต์ที่ได้เป็น UTF-8 ที่ถูกต้องทั้งก้อน
-- (regex ข้างล่างคือไวยากรณ์ UTF-8 ตาม RFC 3629 เขียนเป็นอักษร latin1 ทีละไบต์)
--   · ชื่อไทยที่ถูกอยู่แล้ว (รูปจากฟอร์มแจ้งซ่อม "ฟอร์มแจ้งซ่อม-แถว3.jpg") มีอักษรนอก latin1 → ไม่แตะ
--   · ชื่อที่ตั้งใจใช้อักษร latin1 จริง ๆ อย่าง "café.jpg" แปลงกลับไม่ได้ (é ตามด้วย . ไม่ใช่ UTF-8) → ไม่แตะ
--   · ชื่อ ASCII ล้วนไม่มีอะไรต้องซ่อม → ไม่แตะ (ไม่เขียนแถวโดยเปล่าประโยชน์)
-- เช็คด้วย regex ก่อนแปลง ไม่ใช้ DO block ดักข้อผิดพลาดทีละแถว เพราะ convert_to/convert_from ที่เจอค่าแปลงไม่ได้
-- ล้มทั้ง migration และ scripts/restore-backup.js อ่านคำสั่งจากไฟล์นี้ไปรันซ้ำโดยตัดที่ ; ตัวแรก (DO block มี ; ข้างใน)
-- รันซ้ำได้: ชื่อที่ซ่อมแล้วมีอักษรไทย ซึ่งอยู่นอก latin1 จึงไม่เข้าเงื่อนไขอีก
--
-- ที่อยู่ไฟล์ในถัง (objectKey) ไม่เปลี่ยน — safeName ตัดทุกอักษรที่ไม่ใช่ ASCII ทิ้งอยู่แล้ว ทั้งชื่อเพี้ยนและชื่อไทยได้ key เดียวกัน
-- ไม่ INSERT อะไร → ไม่ต้องเพิ่มชื่อใน SEEDED_BY_MIGRATION แต่ต้องอยู่ใน REPLAY_IF_DUMP_PREDATES ของ restore-backup.js:
-- กู้ไฟล์สำรองที่ทำก่อน migration นี้ลงฐานใหม่ ตารางยังว่างตอน migrate ชื่อเพี้ยนจะกลับมาทั้งหมดถ้าไม่รันซ้ำหลังใส่ข้อมูล

UPDATE "WorkOrderAttachment"
SET "fileName" = convert_from(convert_to("fileName", 'LATIN1'), 'UTF8')
WHERE "fileName" ~ '[\u0080-ÿ]'
  AND "fileName" ~ '^(?:[\u0001-\u007f]|[Â-ß][\u0080-¿]|à[ -¿][\u0080-¿]|[á-ìîï][\u0080-¿]{2}|í[\u0080-\u009f][\u0080-¿]|ð[\u0090-¿][\u0080-¿]{2}|[ñ-ó][\u0080-¿]{3}|ô[\u0080-\u008f][\u0080-¿]{2})*$';

-- ประวัติใบงาน: ข้อความเป็น "<ชนิดไฟล์>: <ชื่อไฟล์>" (ATTACHMENT_KIND_LABELS) — ชนิดไฟล์เป็นอักษรไทยถูกต้องอยู่แล้ว
-- ทั้งข้อความจึงแปลงเป็น latin1 ไม่ได้ ต้องซ่อมเฉพาะส่วนหลัง ": " ตัวแรก (ชื่อชนิดไม่มี ": " อยู่ข้างใน)
-- เฉพาะแนบ/ลบไฟล์ — ประวัติอย่างอื่นไม่เคยมีชื่อไฟล์จากคำขอ จึงไม่มีเหตุให้เพี้ยนแบบนี้
UPDATE "WorkOrderLog"
SET note = left(note, strpos(note, ': ') + 1) || convert_from(convert_to(substr(note, strpos(note, ': ') + 2), 'LATIN1'), 'UTF8')
WHERE action IN ('ATTACHED', 'ATTACHMENT_REMOVED')
  AND strpos(note, ': ') > 0
  AND substr(note, strpos(note, ': ') + 2) ~ '[\u0080-ÿ]'
  AND substr(note, strpos(note, ': ') + 2) ~ '^(?:[\u0001-\u007f]|[Â-ß][\u0080-¿]|à[ -¿][\u0080-¿]|[á-ìîï][\u0080-¿]{2}|í[\u0080-\u009f][\u0080-¿]|ð[\u0090-¿][\u0080-¿]{2}|[ñ-ó][\u0080-¿]{3}|ô[\u0080-\u008f][\u0080-¿]{2})*$';
