-- ตั้งคุณอภิสิทธิ์ (แอดมินที่มีบัญชีอยู่แล้ว) เป็น Super Admin คนแรก ตามที่เจ้าของงานสั่ง
--
-- role เป็นข้อความธรรมดา ไม่ต้องแก้ตาราง แค่เปลี่ยนค่าของบัญชีเดียว
-- หาจากชื่อเพราะไม่ได้รับรหัสพนักงานมา จึงกันพลาดไว้ทุกทาง:
--   - ตั้งเฉพาะเมื่อมีบัญชีชื่อขึ้นต้นด้วย "อภิสิทธิ์" อยู่ "บัญชีเดียว" เท่านั้น (ชื่อซ้ำ = ไม่ตั้งใคร)
--   - บัญชีนั้นต้องเป็นแอดมินอยู่แล้ว (ไม่ยกช่างหรือหัวหน้าภาคขึ้นเป็นเจ้าของระบบ)
--   - ยังไม่มี Super Admin ในระบบ (รันซ้ำหรือมีคนตั้งไว้แล้วจะไม่ทำอะไร)
-- ไม่เข้าเงื่อนไข = ไม่เปลี่ยนอะไรเลย ระบบทำงานแบบเดิม (แอดมินทุกคนตั้งแอดมินได้)
UPDATE "User"
SET "role" = 'SUPER_ADMIN'
WHERE "role" = 'ADMIN'
  AND btrim("name") LIKE 'อภิสิทธิ์%'
  AND (SELECT count(*) FROM "User" WHERE btrim("name") LIKE 'อภิสิทธิ์%') = 1
  AND NOT EXISTS (SELECT 1 FROM "User" WHERE "role" = 'SUPER_ADMIN');
