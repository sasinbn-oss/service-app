-- ลำดับใหม่ (ต.ค. 69): หัวหน้าภาคจ่ายงาน+วัน → แอดมินคอนเฟิร์มลูกค้า → หัวหน้าภาคคอนเฟิร์มออกงาน
--
-- รหัสสถานะเดิมคงไว้ ความหมายเปลี่ยนเป็น
--   PARTS_CHECKED    = รอหัวหน้าภาคจ่ายงาน (เดิม: รอแอดมินนัดลูกค้า)
--   AWAITING_CONFIRM = รอแอดมินคอนเฟิร์มลูกค้า (เดิม: รอลูกค้าคอนเฟิร์มนัด — ยังไม่มีทีม)
--   ASSIGNED         = รอหัวหน้าภาคคอนเฟิร์มออกงาน (เดิม: รอหัวหน้าภาคจ่ายงาน — มีวันแล้ว)
--
-- ใบที่รอคอนเฟิร์มแบบเดิมยังไม่มีทีม แต่ขั้นคอนเฟิร์มแบบใหม่ต้องมีทีมแล้ว (แอดมินโทรบอกร้านว่าทีมไหนจะไป)
-- จึงถอยไปให้หัวหน้าภาคจ่ายงาน — วันที่นัดไว้ยังอยู่ ฟอร์มจ่ายงานตั้งต้นด้วยวันนั้น
-- ใบที่ค้าง PARTS_CHECKED และ ASSIGNED ความหมายใหม่ตรงกับที่ใบนั้นต้องการอยู่แล้ว ไม่ต้องย้าย
UPDATE "WorkOrder" SET "status" = 'PARTS_CHECKED' WHERE "status" = 'AWAITING_CONFIRM' AND "assignedTeam" IS NULL;
