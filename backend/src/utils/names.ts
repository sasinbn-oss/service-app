/**
 * ทำความสะอาดชื่อทีม/ภาค ก่อนเก็บและก่อนเทียบ
 *
 * ขอบเขตหัวหน้าภาคเทียบชื่อทีมแบบตรงทุกตัวอักษร (Branch.zone = User.supervisedTeams) — ชื่อที่มาจากไฟล์ Excel
 * หรือพิมพ์เองบางทีมีช่องว่างท้าย หรืออักษรมองไม่เห็น (zero-width space ที่โปรแกรมพิมพ์ไทยแทรกไว้ตัดคำ)
 * หน้าจอโชว์เหมือนกันเป๊ะ แอดมินติ๊กทีมให้หัวหน้าภาคแล้ว ใบงานของสาขานั้นก็ยังขึ้น "ไม่มีคนรับ"
 * (เจอจริง ต.ค. 69 — "มีทีมแต่ทำไมใบงานไม่เข้าทีม") · ข้อมูลเก่าล้างด้วย migration 20261026090000_clean_team_names
 * ซึ่งใช้กติกาเดียวกัน — แก้ที่นี่ต้องแก้ที่นั่นด้วย
 */
const INVISIBLE = /[​-‍⁠﻿]/g;

export function cleanName(s: string | null | undefined): string | null {
  if (s == null) return null;
  const t = s.normalize("NFC").replace(INVISIBLE, "").replace(/[\s ]+/g, " ").trim();
  return t || null;
}

/**
 * กุญแจหลวม ๆ ไว้หา "ชื่อที่น่าจะตั้งใจให้เป็นทีมเดียวกัน" — ใช้บอกเหตุผลใบไม่มีคนรับเท่านั้น ไม่ใช้ตัดสินขอบเขต
 * ตัดช่องว่างทั้งหมด ตัดคำว่า "ทีม" นำหน้า และรวมพยัญชนะที่สะกดสลับกันบ่อย (ณ/น · ศ/ษ/ส · ฬ/ล)
 * — เจอจริง ต.ค. 69: ทะเบียนสาขาเขียน "พิษณุโลก" บางแถวเขียน "พิษนุโลก" หัวหน้าภาคติ๊กไปชื่อหนึ่ง
 * ใบของอีกชื่อขึ้น "ไม่มีคนรับ" แอดมินดูยังไงก็ไม่เห็นว่าต่างกันตรงไหน
 * ไม่ใช้รวมให้อัตโนมัติ เพราะบางชื่อต่างกันจริง — บอกให้แอดมินรวมเองที่หน้าทีมช่าง (เปลี่ยนชื่อ = รวมทีม)
 */
export function looseKey(s: string | null | undefined): string {
  return (cleanName(s) ?? "")
    .replace(/\s/g, "")
    .replace(/^ทีม/, "")
    .replace(/ณ/g, "น")
    .replace(/[ศษ]/g, "ส")
    .replace(/ฬ/g, "ล")
    .toLowerCase();
}
